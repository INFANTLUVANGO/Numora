export const getCalculator = (slug?: string) => calculators.find((calculator) => calculator.slug === slug)

export const searchCalculators = (query: string) => {
  const normalized = query.trim().toLowerCase()
  if (!normalized) return calculators
  const words = normalized.split(/\s+/)
  return calculators
    .map((calculator) => {
      const haystack = [calculator.title, calculator.shortTitle, calculator.description, calculator.question, calculator.category, ...calculator.tags].join(' ').toLowerCase()
      const score = words.reduce((total, word) => total + (haystack.includes(word) ? 1 : 0), 0)
      return { calculator, score }
    })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score)
    .map(({ calculator }) => calculator)
}
